import path from 'node:path'

import type { Story, StoryModule } from '@astrobook/types'
import type { AstroIntegrationLogger } from 'astro'
import slash from 'slash'

import { invariant } from '../utils/invariant'
import type { PathBuilder } from '../utils/path-builder'

export interface VirtualRoute {
  pattern: string
  /**
   * The absolute path to the virtual entrypoint file. Posix slash format.
   *
   * It's important to use an absolute path here because we must ensure that we
   * only have one `id`, so that Astro's CSS plugin can find the correct CSS
   * content in the following line.
   * https://github.com/withastro/astro/blob/bc2796436dc3810e988c27b71b7a66fcb1ae8bda/packages/astro/src/core/build/plugins/plugin-css.ts#L144
   */
  entrypoint: string
  storyModule: StoryModule
  story: Story
  props: {
    hasSidebar: boolean
    story: string
  }
}

export function getVirtualRoutes(
  storyModules: StoryModule[],
  codegenDir: string,
  logger: AstroIntegrationLogger,
  dashboardSubpath: string,
  previewSubpath: string,
  buildPath: PathBuilder,
): Map<string, VirtualRoute> {
  const routes: VirtualRoute[] = []

  for (const storyModule of storyModules) {
    logger.debug(
      `Found ${storyModule.stories.length} stories in ${storyModule.importPath}`,
    )
    for (const story of storyModule.stories) {
      invariant(
        !story.id.startsWith('..'),
        `Story ID cannot start with '..', but got '${story.id}'`,
      )
      invariant(
        !story.id.startsWith('/'),
        `Story ID cannot start with '/', but got '${story.id}'`,
      )
      routes.push(
        {
          pattern: buildPath(dashboardSubpath, story.id),
          entrypoint: slash(
            path.resolve(codegenDir, 'dashboard', story.id + '.astro'),
          ),
          storyModule,
          story,
          props: { hasSidebar: true, story: story.id },
        },
        {
          pattern: buildPath(previewSubpath, story.id),
          entrypoint: slash(
            path.resolve(codegenDir, 'stories', story.id + '.astro'),
          ),
          storyModule,
          story,
          props: { hasSidebar: false, story: story.id },
        },
      )
    }
  }

  logger.info(`Found ${routes.length} stories in ${storyModules.length} files`)

  return new Map(routes.map((route) => [route.pattern, route]))
}

export function createVirtualRouteComponent(route: VirtualRoute): string {
  // A module name that's useful for debugging and error messages
  const modName = `astrobook_module_${route.storyModule.id}`
    .replaceAll(/\W+/g, '_')
    .replaceAll(/_+/g, '_')
    .replace(/_+$/, '')

  return `
---
// Automatically generated by Astrobook

import type { StoryContext } from '@astrobook/types';
import globalDecorators from 'virtual:astrobook/decorators.mjs';
import StoryPage from 'astrobook/pages/story.astro';
import WithDecorators from 'astrobook/components/with-decorators.astro';
import { getStoryLabels, mergeStoryParameters, parseStoryDefaultExport, parseStoryNamedExport, StoryComponent } from 'astrobook/client';

import * as ${modName} from '${route.storyModule.importPath}';

const { isAstroComponent, title, parameters: defaultParameters } = parseStoryDefaultExport(${modName}, '${route.storyModule.importPath}');
const { name, decorators, args, slots, parameters } = parseStoryNamedExport(${modName}, '${route.storyModule.importPath}', '${route.story.name}');

const labels = getStoryLabels({ name: ${JSON.stringify(route.storyModule.name)}, title }, { name }, ${JSON.stringify(route.story.name)});
const story: StoryContext = {
  id: ${JSON.stringify(route.story.id)},
  name: labels.name,
  module: { ...${JSON.stringify({ id: route.storyModule.id, name: route.storyModule.name, directory: route.storyModule.directory })}, title: labels.title },
  parameters: mergeStoryParameters(defaultParameters, parameters),
};
const allDecorators = [
  ...globalDecorators.map((component) => ({ component, props: { story } })),
  ...(decorators ?? []),
];

// The same hydration props that Astro's compiler adds for \`client:load\`.
const props = isAstroComponent ? args : {
  ...args,
  'client:load': true,
  'client:component-hydration': 'load',
  'client:component-path': '${route.storyModule.importPath}',
  'client:component-export': 'default.component',
};
---

<StoryPage label={story.name} story={'${route.props.story}'} hasSidebar={${route.props.hasSidebar}}>
  <WithDecorators decorators={allDecorators}>
    <StoryComponent component={${modName}.default.component} props={props} slots={slots} />
    {/* Never rendered: Astro bundles an island's client code only for a \`client:*\` directive it compiles. */}
    {false && <${modName}.default.component client:load />}
  </WithDecorators>
</StoryPage>
`.trim()
}
